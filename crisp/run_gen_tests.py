"""
Run tests produced by `python -m crisp.gen_tests` against a Rust translation
in the CRISP sandbox.

Usage, from the project directory:

    uv run --project $CRISP_DIR python -m crisp.run_gen_tests [--code current]

This checks out the Rust code (`--code`, default `current`), the C code
(`--c-code`, needed for its headers) and the generated tests (`--tests`,
default `generated_tests`) into the sandbox, then runs the tests' bundled
`run_tests.py` (see `crisp/gen_tests_runner.py`).  In driver mode, that links
each test driver against the Rust crate's cdylib, so the tests exercise the
translation through its FFI entry points.  Arguments after `--` are passed to
`run_tests.py`, e.g. `-- --compare records --only some_test`.

The result is recorded as a `TestResultNode` tagged `gen_tests_results`, so
`crisp show gen_tests_results` displays the log.

To check the generated tests on every step of the safety loop instead, add
the tests to the C code tree and use the runner as the project's test command:

    crisp checkout generated_tests
    crisp commit -t c_code <your C files...> crisp_tests
    # in crisp.toml:
    test_command = "python3 crisp_tests/run_tests.py"
"""

import argparse
import os
import shlex
import sys

from . import analysis
from .config import Config
from .error import CrispError
from .gen_tests import RUNNER_NAME
from .mvir import MVIR, TreeNode


RESULTS_TAG = 'gen_tests_results'


def find_runner(n_tests: TreeNode) -> str:
    """Find the path of the bundled runner script in the tests tree."""
    runners = sorted(p for p in n_tests.files if os.path.basename(p) == RUNNER_NAME
        and os.path.join(os.path.dirname(p), 'manifest.json') in n_tests.files)
    if len(runners) != 1:
        raise CrispError(f'expected one {RUNNER_NAME} next to a manifest.json in the tests '
            f'tree, but found {len(runners)}; regenerate the tests with `crisp.gen_tests`')
    return runners[0]

def combine_trees(mvir: MVIR, *trees: TreeNode) -> TreeNode:
    """Union of the files in `trees`; later trees win on conflicts."""
    files = {}
    for t in trees:
        files.update(t.files)
    return TreeNode.new(mvir, files = files)

def run_gen_tests(
    cfg: Config,
    mvir: MVIR,
    n_code: TreeNode,
    n_c_code: TreeNode,
    n_tests: TreeNode,
    runner_args: list[str] = (),
):
    runner = find_runner(n_tests)
    cmd = shlex.join(['python3', runner, *runner_args])
    # `run_tests` checks out `code` and `test_code` separately, so the C code
    # and tests go in one tree.  Like the other `@analysis` functions, it
    # reuses a cached result if this exact combination has run before.
    n_test_code = combine_trees(mvir, n_c_code, n_tests)
    n_result = analysis.run_tests(cfg, mvir, n_code, n_test_code, cmd)
    mvir.set_tag(RESULTS_TAG, n_result.node_id(), 'run_gen_tests')
    return n_result


def parse_args(argv = None):
    ap = argparse.ArgumentParser(
        prog = 'python -m crisp.run_gen_tests',
        description = 'Run tests generated by `crisp.gen_tests` against the Rust translation.',
        epilog = 'Arguments after `--` are passed to run_tests.py '
            '(e.g. --compare records, --only NAME, --release).')
    ap.add_argument('--config', '-c', dest = 'config_path', default = 'crisp.toml')
    ap.add_argument('--mvir-storage-dir')
    ap.add_argument('--code', default = 'current',
        help = 'tag or node ID of the Rust code to test (default: %(default)s)')
    ap.add_argument('--c-code', default = 'c_code',
        help = 'tag or node ID of the C code, for its headers (default: %(default)s)')
    ap.add_argument('--tests', default = 'generated_tests',
        help = 'tag or node ID of the generated tests (default: %(default)s)')
    ap.add_argument('runner_args', nargs = argparse.REMAINDER)
    args = ap.parse_args(argv)
    if args.runner_args[:1] == ['--']:
        args.runner_args = args.runner_args[1:]
    return args

def main(argv = None):
    # Imported here to avoid a circular import; `__main__` has the node ID
    # parsing helpers.
    from .__main__ import parse_node_id_arg

    args = parse_args(argv)
    cfg_kwargs = {}
    if args.mvir_storage_dir is not None:
        cfg_kwargs['mvir_storage_dir'] = os.path.abspath(args.mvir_storage_dir)
    cfg = Config.from_toml_file(args.config_path, **cfg_kwargs)
    mvir = MVIR(cfg.mvir_storage_dir, '.')

    nodes = {}
    for what, arg in (('code', args.code), ('c_code', args.c_code), ('tests', args.tests)):
        n = mvir.node(parse_node_id_arg(mvir, arg))
        if not isinstance(n, TreeNode):
            raise CrispError(f'{arg} ({what}) is not a tree')
        nodes[what] = n

    n_result = run_gen_tests(cfg, mvir, nodes['code'], nodes['c_code'], nodes['tests'],
        args.runner_args)

    print()
    print(f'result = {n_result.node_id()} (tag {RESULTS_TAG!r})')
    print('all tests passed' if n_result.passed
        else f'tests failed (exit code {n_result.exit_code}); '
            f'run `crisp show {RESULTS_TAG}` for the log')
    return 0 if n_result.passed else 1

if __name__ == '__main__':
    try:
        sys.exit(main())
    except CrispError as e:
        print(f'error: {e}', file = sys.stderr)
        sys.exit(2)
